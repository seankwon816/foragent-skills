#!/usr/bin/env bash
# Isolated Git Worktree + Deterministic Port & Database Provisioner
# For parallel AI coding agent sessions (Claude Code, OpenAI Codex, OpenCode, Cursor).
#
# Usage:
#   chmod +x scripts/setup-isolated-worktree.sh
#   ./scripts/setup-isolated-worktree.sh <lane-index-1-to-9> <branch-name>
#
# Example:
#   ./scripts/setup-isolated-worktree.sh 1 feat/checkout-discounts
#   ./scripts/setup-isolated-worktree.sh 2 fix/webhook-idempotency
#
# What this solves:
# Spawning two coding agents in git worktrees still breaks integration tests if both worktrees
# bind to localhost:3000 or run migrations against the same local database. This script creates
# the worktree, assigns deterministic port offsets (3001, 5433, 6380...), and writes a scoped
# .env.local so parallel sessions never collide.

set -euo pipefail

if [[ $# -lt 2 ]]; then
  echo "Usage: $0 <lane-index-1-to-9> <branch-name>" >&2
  exit 1
fi

LANE="$1"
BRANCH="$2"

if ! [[ "$LANE" =~ ^[1-9]$ ]]; then
  echo "Error: lane-index must be an integer between 1 and 9 (got: $LANE)." >&2
  exit 1
fi

REPO_ROOT="$(git rev-parse --show-toplevel)"
REPO_NAME="$(basename "$REPO_ROOT")"
SLUG="$(echo "$BRANCH" | tr '/:' '--')"
WORKTREE_DIR="$(dirname "$REPO_ROOT")/${REPO_NAME}-lane-${LANE}-${SLUG}"

APP_PORT=$((3000 + LANE))
API_PORT=$((4000 + LANE))
DB_PORT=$((5432 + LANE))
REDIS_PORT=$((6379 + LANE))
DB_NAME="${REPO_NAME//-/_}_lane_${LANE}"

echo "[worktree] Creating isolated lane #${LANE} at ${WORKTREE_DIR} (branch: ${BRANCH})"
if git show-ref --verify --quiet "refs/heads/${BRANCH}"; then
  git worktree add "$WORKTREE_DIR" "$BRANCH"
else
  git worktree add -b "$BRANCH" "$WORKTREE_DIR"
fi

cat > "${WORKTREE_DIR}/.env.local" <<EOF
# Auto-generated by setup-isolated-worktree.sh for agent lane #${LANE}
AGENT_LANE=${LANE}
PORT=${APP_PORT}
API_PORT=${API_PORT}
DATABASE_URL=postgresql://postgres:postgres@127.0.0.1:${DB_PORT}/${DB_NAME}
REDIS_URL=redis://127.0.0.1:${REDIS_PORT}/0
EOF

echo "[worktree] Wrote isolated environment to ${WORKTREE_DIR}/.env.local"
echo "  APP_PORT=${APP_PORT} | API_PORT=${API_PORT} | DB_NAME=${DB_NAME}"
echo "[worktree] Ready. Start your coding agent inside: cd \"${WORKTREE_DIR}\""
